/** Where "back" goes: staff to the tournament, managers to their teams; public visitors have none. */
function backLink(viewer: ResultsViewer | undefined, role: string | undefined, tournamentId: string, t: { backToTeam: string; backToTournament: string }) {
  if (viewer === 'staff') return { to: `/tournaments/${tournamentId}`, label: t.backToTournament }
  if (viewer === 'manager') return { to: '/dashboard', label: t.backToTeam }
  if (viewer === undefined && role) {
    // Before the data loads (or when it failed): guess from the account role.
    return role === 'MANAGER' ? { to: '/dashboard', label: t.backToTeam } : { to: `/tournaments/${tournamentId}`, label: t.backToTournament }
  }
  return null
}

/** The results API also returns the tournament's public branding (PRO: colour, sponsors, white-label). */
type ResultsWithBranding = ResultsData & { branding?: PublicBranding }

export default function ResultsView({ tournamentId }: { tournamentId: string }) {
  const t = useStrings(STRINGS)
  const lang = useLang()
  const [data, setData] = useState<ResultsWithBranding | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<Error | null>(null)
  const [exporting, setExporting] = useState<string | null>(null)
  const role = useAuthState().user?.role
  // Staff came from the tournament page, managers from their team page; a
  // public visitor (shared link) gets the home page instead.
  const hidePlatform = !!data?.branding?.hidePlatform
  const back = backLink(data?.viewer, role, tournamentId, t) ?? { to: '/', label: hidePlatform ? t.homePlain : t.home }

  const load = useCallback(
    async (isCancelled: () => boolean = () => false) => {
      try {
        const res = await apiGet<ResultsWithBranding>(`/api/tournaments/${tournamentId}/results`)
        if (isCancelled()) return
        setData(res)
        setError(null)
      } catch (e: unknown) {
        if (isCancelled()) return
        setError(e instanceof Error ? e : new Error(STRINGS[useLangStore.getState().lang].couldNotLoad))
      } finally {
        if (!isCancelled()) setLoading(false)
      }
    },
    [tournamentId],
  )

  useEffect(() => {
    let cancelled = false
    void load(() => cancelled)
    return () => {
      cancelled = true
    }
  }, [load])

  async function exportCsv(type: string) {
    if (!data) return
    setExporting(type)
    try {
      const slug = slugify(data.tournament.name)
      await apiDownload(`/api/tournaments/${tournamentId}/export?type=${type}`, `neelamghor-${type}-${slug || 'tournament'}.csv`)
    } catch (e) {
      // Non-fatal for the view, but say why nothing downloaded.
      toast.error(e instanceof ApiError ? e.message : t.downloadFailed)
    } finally {
      setExporting(null)
    }
  }

  if (loading) {
    return (
      <div className="container mx-auto max-w-7xl space-y-4 px-4 py-8">
        <Skeleton className="h-10 w-full max-w-80" />
        <div className="grid grid-cols-2 gap-3 lg:grid-cols-6">
          {Array.from({ length: 6 }).map((_, i) => (
            <Skeleton key={i} className="h-24 rounded-xl" />
          ))}
        </div>
        <Skeleton className="h-96 rounded-xl" />
      </div>
    )
  }

  // A refused or missing report can't be fixed by retrying; anything else (network, server) can.
  const retryable = !!error && !(error instanceof ApiError && [400, 401, 403, 404].includes(error.status))
  if (error && retryable) {
    return (
      <div className="container mx-auto max-w-lg space-y-4 px-4 py-16">
        <LoadError what={t.resultsWhat} error={error} onRetry={() => load()} />
        <div className="text-center">
          <Button variant="ghost" asChild>
            <AppLink href={back.to}>
              <ArrowLeft className="mr-1.5 h-4 w-4" aria-hidden /> {back.label}
            </AppLink>
          </Button>
        </div>
      </div>
    )
  }

  // Private results opened from a shared link while logged out: log in, then come back here.
  if (error instanceof ApiError && error.status === 401 && !role) {
    const here = `/results/${tournamentId}`
    return (
      <div className="container mx-auto max-w-lg px-4 py-16">
        <EmptyState
          icon={Lock}
          title={t.loginTitle}
          description={t.loginDesc}
          action={
            <Button asChild>
              <AppLink href="/login" onClick={() => setReturnTo(here)}>
                <LogIn className="mr-1.5 h-4 w-4" aria-hidden /> {t.loginCta}
              </AppLink>
            </Button>
          }
        />
      </div>
    )
  }

  if (error || !data) {
    return (
      <div className="container mx-auto max-w-lg px-4 py-16">
        <EmptyState
          icon={ShieldAlert}
          title={t.unavailable}
          description={error?.message ?? t.noResultsYet}
          action={
            <Button variant="outline" asChild>
              <AppLink href={back.to}>{back.label}</AppLink>
            </Button>
          }
        />
      </div>
    )
  }

  const { tournament, summary, teams, recentBids } = data
  const isPublicViewer = data.viewer === 'public'
  const teamById = new Map(teams.map((team) => [team.id, team]))
  const topBuys = teams
    .flatMap((team) => team.players)
    .filter((p) => p.soldPrice != null)
    .sort((a, b) => (b.soldPrice ?? 0) - (a.soldPrice ?? 0) || a.playerNumber - b.playerNumber)
    .slice(0, 5)
  const allTeamsFilled = teams.length > 0 && teams.every((team) => team.players.length >= team.minSquad)
  const branding = data.branding ?? null
  // Brand colour (PRO) as fills with a computed black/white foreground — never as text.
  const brand = branding?.brandColor ? brandPalette(branding.brandColor) : null

  return (
    <div className="container mx-auto max-w-7xl px-4 py-6 sm:py-8 print:max-w-none print:px-0">
      {/* print-only report header */}
      <div className="mb-4 hidden text-center print:block">
        <p className="text-lg font-black">{hidePlatform ? t.reportTitlePlain : t.reportTitle}</p>
        <p className="text-sm">
          {tournament.name} · {sportLabel(tournament.sport, lang)}
          {tournament.roomCode ? t.roomSuffix(tournament.roomCode) : ''} · {formatDate(tournament.startDate, false, lang)}
        </p>
      </div>

      <header className="flex flex-col gap-3 md:flex-row md:items-start md:justify-between">
        <div>
          <Button variant="ghost" size="sm" className="-ml-2 mb-1 text-muted-foreground print:hidden" asChild>
            <AppLink href={back.to}>
              <ArrowLeft className="mr-1 h-4 w-4" aria-hidden /> {back.label}
            </AppLink>
          </Button>
          {brand ? <span aria-hidden className="mb-2 block h-1.5 w-14 rounded-full" style={{ backgroundColor: brand.bg }} /> : null}
          <div className="flex items-center gap-3">
            {branding?.logoUrl ? (
              <img
                src={branding.logoUrl}
                alt=""
                className="h-12 w-12 shrink-0 rounded-xl border bg-white object-contain p-1 sm:h-14 sm:w-14"
              />
            ) : null}
            <div className="flex min-w-0 flex-wrap items-center gap-2">
              <h1 className="text-2xl font-black tracking-tight sm:text-3xl">{tournament.name}</h1>
              <TournamentStatusBadge status={tournament.status} />
            </div>
          </div>
          <div className="mt-1.5 flex flex-wrap items-center gap-x-3 gap-y-1 text-sm text-muted-foreground">
            <span className="flex items-center gap-1">
              <Trophy className="h-3.5 w-3.5" aria-hidden />
              {sportLabel(tournament.sport, lang)}
            </span>
            {tournament.roomCode ? (
              <Badge variant="outline" className="font-mono text-xs tracking-[0.18em]">{tournament.roomCode}</Badge>
            ) : null}
            <span>{formatDate(tournament.startDate, false, lang)}</span>
            {tournament.location ? <span>{tournament.location}</span> : null}
          </div>
        </div>
        <div className="flex shrink-0 flex-wrap gap-2 print:hidden">
          {/* Staff and managers always see the league page; anyone else only while it is public. */}
          {data.viewer !== 'public' || data.resultsPublic ? (
            <Button variant="outline" asChild>
              <AppLink href={`/league/${tournament.id}`}>
                <CalendarRange className="mr-2 h-4 w-4" aria-hidden /> {t.fixturesTable}
              </AppLink>
            </Button>
          ) : null}
          <Button variant="outline" onClick={() => window.print()}>
            <Printer className="mr-2 h-4 w-4" /> {t.printReport}
          </Button>
          {/* CSV export is the organizer's (server-enforced); managers get the report only. */}
          {data.canManage ? (
          <DropdownMenu>
            <DropdownMenuTrigger asChild>
              <Button>
                {exporting ? <Loader2 className="mr-2 h-4 w-4 animate-spin" aria-hidden /> : <Download className="mr-2 h-4 w-4" aria-hidden />}
                {t.exportLabel}
              </Button>
            </DropdownMenuTrigger>
            <DropdownMenuContent align="end" className="w-56">
              <DropdownMenuLabel className="text-xs">{t.downloadData}</DropdownMenuLabel>
              <DropdownMenuSeparator />
              {EXPORT_TYPES.map((type) => (
                <DropdownMenuItem key={type} onClick={() => void exportCsv(type)}>
                  {t.exportTypes[type]}
                </DropdownMenuItem>
              ))}
            </DropdownMenuContent>
          </DropdownMenu>
          ) : null}
        </div>
      </header>

      {data.viewer === 'staff' ? (
        <p className="mt-4 flex items-start gap-2 rounded-lg border bg-muted/40 px-3 py-2 text-xs text-muted-foreground print:hidden">
          {data.resultsPublic ? <Globe className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden /> : <Lock className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />}
          <span>{!data.resultsPublic ? t.staffPrivate : data.publicNow ? t.staffPublic : t.staffPublicLater}</span>
        </p>
      ) : null}

      {data.publicNow ? <ShareBar tournamentId={tournament.id} name={tournament.name} hidePlatform={hidePlatform} t={t} /> : null}

      {branding && branding.sponsors.length > 0 ? (
        <SponsorStrip sponsors={branding.sponsors} variant="page" brandColor={branding.brandColor} className="mt-4 print:break-inside-avoid" />
      ) : null}

      {/* summary */}
      <div className="mt-6 grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-6">
        <StatCard label={t.totalPlayers} value={summary.totalPlayers} />
        <StatCard label={t.sold} value={summary.sold} tone="success" />
        <StatCard label={t.unsold} value={summary.unsold} tone="danger" />
        <StatCard label={t.teams} value={summary.teams} />
        <StatCard label={t.totalBids} value={summary.totalBids} tone="primary" />
        <StatCard label={t.auctionValue} value={formatBDT(summary.totalValue)} tone="warning" />
      </div>

      {allTeamsFilled ? (
        <div className="mt-5 flex items-center justify-center gap-2 rounded-xl border border-teal-200 bg-teal-50 px-4 dark:border-teal-900/60 dark:bg-teal-950/40 py-3 text-center print:break-inside-avoid">
          <Trophy className="h-5 w-5 shrink-0 text-teal-700 dark:text-teal-300" aria-hidden />
          <p className="text-sm font-bold text-teal-900 dark:text-teal-200">
            {t.allFilled}
          </p>
        </div>
      ) : null}

      {/* top buys */}
      {topBuys.length > 0 ? (
        <section className="mt-8 print:break-inside-avoid" aria-label={t.topBuys}>
          <h2 className="mb-3 text-lg font-black tracking-tight print:text-base">{t.topBuys}</h2>
          <ol className="grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
            {topBuys.map((p, i) => {
              const team = p.soldToTeamId ? teamById.get(p.soldToTeamId) : undefined
              return (
                <li key={p.id} className="relative flex items-center gap-3 rounded-xl border bg-card p-3 shadow-sm lg:flex-col lg:items-start">
                  <span
                    className={cn(
                      'flex h-8 w-8 shrink-0 items-center justify-center rounded-full text-sm font-black',
                      i === 0 ? (brand ? '' : 'bg-amber-400 text-amber-950') : 'bg-muted text-muted-foreground',
                    )}
                    style={i === 0 && brand ? { backgroundColor: brand.bg, color: brand.fg } : undefined}
                  >
                    {i + 1}
                  </span>
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-sm font-bold">{p.name}</p>
                    {team ? (
                      <p className="flex items-center gap-1.5 truncate text-xs text-muted-foreground">
                        <TeamAvatar name={team.name} color={team.color} logoUrl={team.logoUrl} className="h-4 w-4" />
                        {t.soldTo(team.name)}
                      </p>
                    ) : null}
                  </div>
                  <span className="shrink-0 text-base font-black tabular-nums text-teal-700 dark:text-teal-300">{formatBDT(p.soldPrice)}</span>
                  {data.publicNow && team && p.soldPrice != null ? (
                    <ShareSaleButton
                      iconOnly
                      className="shrink-0 print:hidden lg:absolute lg:right-3 lg:top-3"
                      path={`/results/${tournament.id}`}
                      sale={{ playerId: p.id, playerName: p.name, teamName: team.name, price: p.soldPrice }}
                    />
                  ) : null}
                </li>
              )
            })}
          </ol>
        </section>
      ) : null}

      {/* final squads */}
      <section className="mt-8" aria-label={t.finalSquads}>
        <h2 className="mb-3 text-lg font-black tracking-tight print:text-base">{t.finalSquads}</h2>
        {teams.length === 0 ? (
          <EmptyState icon={Gavel} title={t.noTeams} description={t.noTeamsDesc} />
        ) : (
          <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3 print:grid print:grid-cols-3 print:gap-2">
            {teams.map((team) => {
              const spendPct = team.budget > 0 ? Math.min(100, (team.spent / team.budget) * 100) : 0
              const players = [...team.players].sort((a, b) => (b.soldPrice ?? 0) - (a.soldPrice ?? 0))
              return (
                <Card key={team.id} className="break-inside-avoid print:break-inside-avoid">
                  <CardHeader className="pb-2">
                    <CardTitle className="flex items-center gap-2.5 text-base">
                      <TeamAvatar name={team.name} color={team.color} logoUrl={team.logoUrl} className="h-9 w-9" />
                      <span className="min-w-0 flex-1 truncate">{team.name}</span>
                      <Badge variant="secondary" className="tabular-nums">{team.players.length}/{team.maxSquad}</Badge>
                    </CardTitle>
                    <div className="mt-1 space-y-1">
                      <Progress value={spendPct} className="h-1.5" aria-label={t.budgetUsedAria(team.name)} />
                      <p className="text-[11px] text-muted-foreground tabular-nums">
                        {t.spent} <span className="font-bold text-foreground">{formatBDT(team.spent)}</span> {t.ofBudget(formatBDT(team.budget))} · {t.left}{' '}
                        <span className="font-bold text-emerald-700 dark:text-emerald-400">{formatBDT(team.remaining)}</span>
                      </p>
                    </div>
                  </CardHeader>
                  <CardContent className="p-0">
                    <ul className="max-h-96 divide-y overflow-y-auto print:max-h-none print:overflow-visible" aria-label={t.squadAria(team.name)}>
                      {players.length === 0 ? (
                        <li className="px-4 py-6 text-center text-sm text-muted-foreground">{t.noPlayersBought}</li>
                      ) : null}
                      {players.map((p) => (
                        <li key={p.id} className="flex items-center gap-2 px-4 py-2">
                          <span className="w-8 shrink-0 font-mono text-[11px] font-bold tabular-nums text-muted-foreground">
                            #{String(p.playerNumber).padStart(3, '0')}
                          </span>
                          <div className="min-w-0 flex-1">
                            <p className="truncate text-sm font-semibold">{p.name}</p>
                            <p className="truncate text-xs text-muted-foreground">
                              <PlayerRole role={p.role} />
                              {p.category ? t.cat(p.category) : ''}
                            </p>
                          </div>
                          <span className="shrink-0 text-sm font-bold tabular-nums text-teal-700 dark:text-teal-300">
                            {formatBDT(p.soldPrice ?? p.basePrice)}
                          </span>
                        </li>
                      ))}
                    </ul>
                    <p className={cn('border-t px-4 py-2 text-xs text-muted-foreground tabular-nums print:border-t')}>
                      {t.teamFooter(team.players.length, team.minSquad)}{' '}
                      {team.players.length > 0 ? formatBDT(team.spent / team.players.length) : '—'}
                    </p>
                  </CardContent>
                </Card>
              )
            })}
          </div>
        )}
      </section>

      {/* recent bids */}
      <section className="mt-8 print:break-inside-avoid" aria-label={t.recentBids}>
        <h2 className="mb-3 text-lg font-black tracking-tight print:text-base">{t.recentBids}</h2>
        <Card>
          <CardContent className="p-0">
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b text-left text-xs uppercase tracking-wide text-muted-foreground">
                    <th className="px-3 py-2.5 font-semibold sm:px-4">{t.colTime}</th>
                    <th className="px-3 py-2.5 font-semibold sm:px-4">{t.colPlayer}</th>
                    <th className="px-3 py-2.5 font-semibold sm:px-4">{t.colTeam}</th>
                    <th className="px-3 py-2.5 text-right font-semibold sm:px-4">{t.colAmount}</th>
                  </tr>
                </thead>
                <tbody className="divide-y">
                  {recentBids.length === 0 ? (
                    <tr>
                      <td colSpan={4} className="px-4 py-8 text-center text-muted-foreground">
                        {t.noBids}
                      </td>
                    </tr>
                  ) : null}
                  {recentBids.map((b, i) => (
                    <tr key={`${b.createdAt}-${i}`} className="hover:bg-muted/40">
                      <td className="whitespace-nowrap px-3 py-2 tabular-nums text-muted-foreground sm:px-4">{formatTime(b.createdAt, lang)}</td>
                      <td className="px-3 py-2 font-semibold break-words sm:px-4">{b.playerName}</td>
                      <td className="px-3 py-2 break-words sm:px-4">{b.teamName}</td>
                      <td className="whitespace-nowrap px-3 py-2 text-right font-bold tabular-nums text-teal-700 sm:px-4 dark:text-teal-300">{formatBDT(b.amount)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </CardContent>
        </Card>
      </section>

      {/* Shared-link visitors: what this is, and how to run one */}
      {isPublicViewer && !role && !hidePlatform ? (
        <section className="mt-10 rounded-2xl bg-gradient-to-br from-teal-700 via-teal-800 to-emerald-900 px-6 py-8 text-center text-white shadow-lg print:hidden">
          <h2 className="text-xl font-extrabold tracking-tight sm:text-2xl">{t.ctaTitle}</h2>
          <p className="mx-auto mt-2 max-w-xl text-sm text-teal-100">{t.ctaSub}</p>
          <Button size="lg" variant="secondary" className="mt-5 min-h-11 bg-white text-teal-900 hover:bg-teal-50" asChild>
            <AppLink href="/register">
              <Rocket className="mr-1.5 h-4 w-4" aria-hidden /> {t.ctaButton}
            </AppLink>
          </Button>
        </section>
      ) : null}

      {/* print footer */}
      <p className="mt-6 hidden text-center text-xs text-muted-foreground print:block">
        {hidePlatform ? t.generatedOn(formatDate(new Date(), true, lang)) : t.generatedBy(formatDate(new Date(), true, lang))}
      </p>

      {/* print tuning — report-only chrome, white background, avoid card page breaks */}
      <style
        dangerouslySetInnerHTML={{
          __html: `@media print {
            html, body { background: #fff !important; }
            body { font-size: 12.5px; }
            .break-inside-avoid { break-inside: avoid; page-break-inside: avoid; }
          }`,
        }}
      />
    </div>
  )
}

type ShareStrings = (typeof STRINGS)['en']

/** WhatsApp / Facebook / copy link / download the share card (the /api/og image). */
function ShareBar({
  tournamentId,
  name,
  hidePlatform,
  t,
}: {
  tournamentId: string
  name: string
  /** White-label (PRO): no "on NeelamGhor" in the shared text or file name. */
  hidePlatform: boolean
  t: ShareStrings
}) {
  // Rendered only once the results have loaded (client side), so `window` is there.
  const url = typeof window === 'undefined' ? `/results/${tournamentId}` : `${window.location.origin}/results/${tournamentId}`
  const text = hidePlatform ? t.shareTextPlain(name) : t.shareText(name)
  const card = `/api/og/results/${encodeURIComponent(tournamentId)}`

  async function copy() {
    try {
      await navigator.clipboard.writeText(url)
      toast.success(t.linkCopied)
    } catch {
      toast.error(t.copyFailed)
    }
  }

  return (
    <div className="mt-4 flex flex-wrap items-center gap-2 rounded-xl border bg-card px-3 py-2.5 shadow-sm print:hidden" role="group" aria-label={t.shareTitle}>
      <span className="mr-1 flex items-center gap-1.5 text-sm font-semibold">
        <Share2 className="h-4 w-4 text-primary" aria-hidden /> {t.shareTitle}
      </span>
      <Button size="sm" className="bg-[#1f9d55] text-white hover:bg-[#1a8a4a]" asChild>
        <a href={`https://wa.me/?text=${encodeURIComponent(`${text} ${url}`)}`} target="_blank" rel="noopener noreferrer">
          <MessageCircle className="mr-1.5 h-4 w-4" aria-hidden /> {t.whatsapp}
        </a>
      </Button>
      <Button size="sm" className="bg-[#1877f2] text-white hover:bg-[#1468d8]" asChild>
        <a href={`https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`} target="_blank" rel="noopener noreferrer">
          <Share2 className="mr-1.5 h-4 w-4" aria-hidden /> {t.facebook}
        </a>
      </Button>
      <Button size="sm" variant="outline" onClick={() => void copy()}>
        <Copy className="mr-1.5 h-4 w-4" aria-hidden /> {t.copyLink}
      </Button>
      <Button size="sm" variant="outline" asChild>
        <a href={card} download={`${hidePlatform ? '' : 'neelamghor-'}results-${slugify(name) || 'tournament'}.png`}>
          <ImageDown className="mr-1.5 h-4 w-4" aria-hidden /> {t.downloadCard}
        </a>
      </Button>
    </div>
  )
}
