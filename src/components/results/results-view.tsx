export default function ResultsView({ tournamentId }: { tournamentId: string }) {
  const t = useStrings(STRINGS)
  const lang = useLang()
  const [data, setData] = useState<ResultsData | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [exporting, setExporting] = useState<string | null>(null)
  // Organizers and admins came from the tournament page; managers from their team page.
  const role = useAppStore((s) => s.user?.role)
  const back = role === 'MANAGER'
    ? { to: '/dashboard', label: t.backToTeam }
    : { to: `/tournaments/${tournamentId}`, label: t.backToTournament }

  useEffect(() => {
    let cancelled = false
    apiGet<ResultsData>(`/api/tournaments/${tournamentId}/results`)
      .then((res) => {
        if (!cancelled) setData(res)
      })
      .catch((e: unknown) => {
        if (!cancelled) setError(e instanceof ApiError ? e.message : STRINGS[useLangStore.getState().lang].couldNotLoad)
      })
      .finally(() => {
        if (!cancelled) setLoading(false)
      })
    return () => {
      cancelled = true
    }
  }, [tournamentId])

  async function exportCsv(type: string) {
    if (!data) return
    setExporting(type)
    try {
      const slug = slugify(data.tournament.name)
      await apiDownload(`/api/tournaments/${tournamentId}/export?type=${type}`, `neelamghor-${type}-${slug || 'tournament'}.csv`)
    } catch (e) {
      // Non-fatal for the view, but say why nothing downloaded.
      toast.error(e instanceof ApiError ? e.message : t.downloadFailed)
    } finally {
      setExporting(null)
    }
  }

  if (loading) {
    return (
      <div className="container mx-auto max-w-7xl space-y-4 px-4 py-8">
        <Skeleton className="h-10 w-80" />
        <div className="grid grid-cols-2 gap-3 lg:grid-cols-6">
          {Array.from({ length: 6 }).map((_, i) => (
            <Skeleton key={i} className="h-24 rounded-xl" />
          ))}
        </div>
        <Skeleton className="h-96 rounded-xl" />
      </div>
    )
  }

  if (error || !data) {
    return (
      <div className="container mx-auto max-w-lg px-4 py-16">
        <EmptyState
          icon={ShieldAlert}
          title={t.unavailable}
          description={error ?? t.noResultsYet}
          action={
            <Button variant="outline" onClick={() => navigate(back.to)}>
              {back.label}
            </Button>
          }
        />
      </div>
    )
  }

  const { tournament, summary, teams, recentBids } = data
  const allTeamsFilled = teams.length > 0 && teams.every((team) => team.players.length >= team.minSquad)

  return (
    <div className="container mx-auto max-w-7xl px-4 py-6 sm:py-8 print:max-w-none print:px-0">
      {/* print-only report header */}
      <div className="mb-4 hidden text-center print:block">
        <p className="text-lg font-black">{t.reportTitle}</p>
        <p className="text-sm">
          {tournament.name} · {sportLabel(tournament.sport, lang)}
          {tournament.roomCode ? t.roomSuffix(tournament.roomCode) : ''} · {formatDate(tournament.startDate)}
        </p>
      </div>

      <header className="flex flex-col gap-3 md:flex-row md:items-start md:justify-between">
        <div>
          <Button
            variant="ghost"
            size="sm"
            className="-ml-2 mb-1 text-muted-foreground print:hidden"
            onClick={() => navigate(back.to)}
          >
            <ArrowLeft className="mr-1 h-4 w-4" aria-hidden /> {back.label}
          </Button>
          <div className="flex flex-wrap items-center gap-2">
            <h1 className="text-2xl font-black tracking-tight sm:text-3xl">{tournament.name}</h1>
            <TournamentStatusBadge status={tournament.status} />
          </div>
          <div className="mt-1.5 flex flex-wrap items-center gap-x-3 gap-y-1 text-sm text-muted-foreground">
            <span className="flex items-center gap-1">
              <Trophy className="h-3.5 w-3.5" aria-hidden />
              {sportLabel(tournament.sport, lang)}
            </span>
            {tournament.roomCode ? (
              <Badge variant="outline" className="font-mono text-xs tracking-[0.18em]">{tournament.roomCode}</Badge>
            ) : null}
            <span>{formatDate(tournament.startDate)}</span>
            {tournament.location ? <span>{tournament.location}</span> : null}
          </div>
        </div>
        <div className="flex shrink-0 gap-2 print:hidden">
          <Button variant="outline" onClick={() => window.print()}>
            <Printer className="mr-2 h-4 w-4" /> {t.printReport}
          </Button>
          {/* CSV export is the organizer's (server-enforced); managers get the report only. */}
          {data.canManage ? (
          <DropdownMenu>
            <DropdownMenuTrigger asChild>
              <Button>
                {exporting ? <Loader2 className="mr-2 h-4 w-4 animate-spin" aria-hidden /> : <Download className="mr-2 h-4 w-4" aria-hidden />}
                {t.exportLabel}
              </Button>
            </DropdownMenuTrigger>
            <DropdownMenuContent align="end" className="w-56">
              <DropdownMenuLabel className="text-xs">{t.downloadData}</DropdownMenuLabel>
              <DropdownMenuSeparator />
              {EXPORT_TYPES.map((type) => (
                <DropdownMenuItem key={type} onClick={() => void exportCsv(type)}>
                  {t.exportTypes[type]}
                </DropdownMenuItem>
              ))}
            </DropdownMenuContent>
          </DropdownMenu>
          ) : null}
        </div>
      </header>

      {/* summary */}
      <div className="mt-6 grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-6">
        <StatCard label={t.totalPlayers} value={summary.totalPlayers} />
        <StatCard label={t.sold} value={summary.sold} tone="success" />
        <StatCard label={t.unsold} value={summary.unsold} tone="danger" />
        <StatCard label={t.teams} value={summary.teams} />
        <StatCard label={t.totalBids} value={summary.totalBids} tone="primary" />
        <StatCard label={t.auctionValue} value={formatBDT(summary.totalValue)} tone="warning" />
      </div>

      {allTeamsFilled ? (
        <div className="mt-5 flex items-center justify-center gap-2 rounded-xl border border-teal-200 bg-teal-50 px-4 py-3 text-center print:break-inside-avoid">
          <Trophy className="h-5 w-5 shrink-0 text-teal-700" aria-hidden />
          <p className="text-sm font-bold text-teal-900">
            {t.allFilled}
          </p>
        </div>
      ) : null}

      {/* final squads */}
      <section className="mt-8" aria-label={t.finalSquads}>
        <h2 className="mb-3 text-lg font-black tracking-tight print:text-base">{t.finalSquads}</h2>
        {teams.length === 0 ? (
          <EmptyState icon={Gavel} title={t.noTeams} description={t.noTeamsDesc} />
        ) : (
          <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3 print:grid print:grid-cols-3 print:gap-2">
            {teams.map((team) => {
              const spendPct = team.budget > 0 ? Math.min(100, (team.spent / team.budget) * 100) : 0
              const players = [...team.players].sort((a, b) => (b.soldPrice ?? 0) - (a.soldPrice ?? 0))
              return (
                <Card key={team.id} className="break-inside-avoid print:break-inside-avoid">
                  <CardHeader className="pb-2">
                    <CardTitle className="flex items-center gap-2.5 text-base">
                      <TeamAvatar name={team.name} color={team.color} logoUrl={team.logoUrl} className="h-9 w-9" />
                      <span className="min-w-0 flex-1 truncate">{team.name}</span>
                      <Badge variant="secondary" className="tabular-nums">{team.players.length}/{team.maxSquad}</Badge>
                    </CardTitle>
                    <div className="mt-1 space-y-1">
                      <Progress value={spendPct} className="h-1.5" aria-label={t.budgetUsedAria(team.name)} />
                      <p className="text-[11px] text-muted-foreground tabular-nums">
                        {t.spent} <span className="font-bold text-foreground">{formatBDT(team.spent)}</span> {t.ofBudget(formatBDT(team.budget))} · {t.left}{' '}
                        <span className="font-bold text-emerald-700">{formatBDT(team.remaining)}</span>
                      </p>
                    </div>
                  </CardHeader>
                  <CardContent className="p-0">
                    <ul className="max-h-96 divide-y overflow-y-auto print:max-h-none print:overflow-visible" aria-label={t.squadAria(team.name)}>
                      {players.length === 0 ? (
                        <li className="px-4 py-6 text-center text-sm text-muted-foreground">{t.noPlayersBought}</li>
                      ) : null}
                      {players.map((p) => (
                        <li key={p.id} className="flex items-center gap-2 px-4 py-2">
                          <span className="w-8 shrink-0 font-mono text-[11px] font-bold tabular-nums text-muted-foreground">
                            #{String(p.playerNumber).padStart(3, '0')}
                          </span>
                          <div className="min-w-0 flex-1">
                            <p className="truncate text-sm font-semibold">{p.name}</p>
                            <p className="truncate text-xs text-muted-foreground">
                              {p.role}
                              {p.category ? t.cat(p.category) : ''}
                            </p>
                          </div>
                          <span className="shrink-0 text-sm font-bold tabular-nums text-teal-700">
                            {formatBDT(p.soldPrice ?? p.basePrice)}
                          </span>
                        </li>
                      ))}
                    </ul>
                    <p className={cn('border-t px-4 py-2 text-xs text-muted-foreground tabular-nums print:border-t')}>
                      {t.teamFooter(team.players.length, team.minSquad)}{' '}
                      {team.players.length > 0 ? formatBDT(team.spent / team.players.length) : '—'}
                    </p>
                  </CardContent>
                </Card>
              )
            })}
          </div>
        )}
      </section>

      {/* recent bids */}
      <section className="mt-8 print:break-inside-avoid" aria-label={t.recentBids}>
        <h2 className="mb-3 text-lg font-black tracking-tight print:text-base">{t.recentBids}</h2>
        <Card>
          <CardContent className="p-0">
            <div className="overflow-x-auto">
              <table className="w-full min-w-[480px] text-sm">
                <thead>
                  <tr className="border-b text-left text-xs uppercase tracking-wide text-muted-foreground">
                    <th className="px-4 py-2.5 font-semibold">{t.colTime}</th>
                    <th className="px-4 py-2.5 font-semibold">{t.colPlayer}</th>
                    <th className="px-4 py-2.5 font-semibold">{t.colTeam}</th>
                    <th className="px-4 py-2.5 text-right font-semibold">{t.colAmount}</th>
                  </tr>
                </thead>
                <tbody className="divide-y">
                  {recentBids.length === 0 ? (
                    <tr>
                      <td colSpan={4} className="px-4 py-8 text-center text-muted-foreground">
                        {t.noBids}
                      </td>
                    </tr>
                  ) : null}
                  {recentBids.map((b, i) => (
                    <tr key={`${b.createdAt}-${i}`} className="hover:bg-muted/40">
                      <td className="whitespace-nowrap px-4 py-2 tabular-nums text-muted-foreground">{formatTime(b.createdAt)}</td>
                      <td className="px-4 py-2 font-semibold">{b.playerName}</td>
                      <td className="px-4 py-2">{b.teamName}</td>
                      <td className="px-4 py-2 text-right font-bold tabular-nums text-teal-700">{formatBDT(b.amount)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </CardContent>
        </Card>
      </section>

      {/* print footer */}
      <p className="mt-6 hidden text-center text-xs text-muted-foreground print:block">
        {t.generatedBy(formatDate(new Date(), true))}
      </p>

      {/* print tuning — report-only chrome, white background, avoid card page breaks */}
      <style
        dangerouslySetInnerHTML={{
          __html: `@media print {
            html, body { background: #fff !important; }
            body { font-size: 12.5px; }
            .break-inside-avoid { break-inside: avoid; page-break-inside: avoid; }
          }`,
        }}
      />
    </div>
  )
}
